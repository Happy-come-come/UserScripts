const fs = require('node:fs');
const path = require('node:path');

const versionsDir = path.join(__dirname, 'versions');
const files = ['text.js', 'styles.js', 'rich.js', 'profile-hover.js', 'tweet-element-builder-core.js'];

for(const entry of fs.readdirSync(versionsDir, {withFileTypes: true})){
	if(!entry.isDirectory() || !/^\d{4}-\d{2}-\d{2}$/.test(entry.name))continue;
	const sourceDir = path.join(versionsDir, entry.name);
	const missing = files.filter(file => !fs.existsSync(path.join(sourceDir, file)));
	if(missing.length)throw new Error(`${entry.name}: missing ${missing.join(', ')}`);
	const header = `/* Generated by builders/twitterElementBuilders/tweetElementBuilder/build-versions.cjs. Do not edit.\n * Version: ${entry.name}; sources: ${files.join(', ')}\n */\n`;
	const body = files.map(file => `\n/* ${file} */\n${fs.readFileSync(path.join(sourceDir, file), 'utf8')}\n`).join(';\n');
	const target = path.join(sourceDir, `TEB-v${entry.name}.js`);
	fs.writeFileSync(target, `${header}(function(){\nconst module = undefined;\n${body}\n})();\n`);
	console.log(path.relative(__dirname, target));
}
