const fs = require('node:fs');
const path = require('node:path');
const versionsDir = path.join(__dirname, 'versions');
for(const entry of fs.readdirSync(versionsDir, {withFileTypes: true})){
	if(!entry.isDirectory() || !/^\d{4}-\d{2}-\d{2}$/.test(entry.name))continue;
	const version = entry.name, sourceDir = path.join(versionsDir, version);
	const target = path.join(sourceDir, `TLB-v${version}.js`);
	const source = fs.readFileSync(path.join(sourceDir, 'tl-builder.js'), 'utf8');
	const userBuilderPath = path.join(sourceDir, 'user-element-builder.js');
	const userBuilder = fs.existsSync(userBuilderPath) ? fs.readFileSync(userBuilderPath, 'utf8') : '';
	fs.writeFileSync(target, `/* Generated by builders/twitterElementBuilders/TLBuilder/build-versions.cjs. Do not edit. */\n${userBuilder}\n${source}\n`);
	console.log(path.relative(__dirname, target));
}
